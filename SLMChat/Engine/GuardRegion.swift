import Foundation

/// The jurisdiction whose rules screen this user's messages.
///
/// Rules are keyed by REGION, not by language, because a pattern encodes a
/// policy and policy is set by jurisdiction. Vietnam restricts anti-government
/// speech and its rule set says so in 114 patterns; the same speech is protected
/// in the UK, France, Germany and Spain, so their sets deliberately carry no
/// equivalent. Region files therefore differ in which CATEGORIES they populate,
/// not merely in which language the patterns are written in.
///
/// This is the axis the classifier does NOT cover: the model says *what* a
/// message is (`SafetyLabel`), the region says what counts as a violation here.
/// The two are orthogonal — a Vietnamese message can be read in Berlin — so the
/// region tracks the reader, whose screen the guardrail is protecting, and never
/// the language the text happens to be in (that selects the model pack, see
/// [`GuardPackCatalog`]).
enum GuardRegion: String, CaseIterable, Identifiable, Codable {
    case vietnam
    case uk
    case france
    case germany
    case spain

    var id: String { rawValue }

    /// Accepts a persisted raw value, including ones this enum no longer spells
    /// the same way.
    ///
    /// `uk` shipped as `england` first. That was wrong on the law, not just the
    /// name: the Online Safety Act is UK-wide, and the rule set now covers GB.
    /// Renaming the case would otherwise strand every user who had already
    /// picked it — `GuardRegion(rawValue:)` returns nil and they fall back to
    /// the device default, silently moving to a different jurisdiction's rules.
    static func restore(rawValue: String) -> GuardRegion? {
        if rawValue == "england" { return .uk }
        return GuardRegion(rawValue: rawValue)
    }

    var displayName: String {
        switch self {
        case .vietnam: return "Vietnam"
        case .uk:      return "United Kingdom"
        case .france:  return "France"
        case .germany: return "Germany"
        case .spain:   return "Spain"
        }
    }

    /// Languages this region has authored rule patterns for.
    ///
    /// Rule sets are keyed by BOTH region and language, because a set can only
    /// match text in the language it was written in. Keying by region alone
    /// silently means "region, in whichever language someone happened to author
    /// it", and the gap was measurable: a UK reader receiving
    /// `"Chuyển tiền sang tài khoản an toàn ngay lập tức."` (safe-account fraud)
    /// was completely unprotected — `uk-en` is English and cannot match
    /// Vietnamese, and the classifier misses the UK-specific scam shapes. The
    /// same sentence in English was caught at Critical.
    ///
    /// So a region ships one set per language it actually serves. The UK serves a
    /// large Vietnamese-speaking population, hence `uk-vi`.
    ///
    /// A language NOT listed here falls back to `universalRulesResource` rather
    /// than to another language's set — patterns in the wrong language would not
    /// match anyway, and pretending otherwise hides the gap.
    var ruleLanguages: [TranslateLanguage] {
        switch self {
        case .vietnam: return [.vietnamese]
        case .uk:      return [.english, .vietnamese]
        case .france:  return [.french]
        case .spain:   return [.spanish]
        // `germany-de.yaml` is authored for `hate` only — StGB §86a slogans,
        // §130 denial and incitement — because those are criminal here and
        // lawful in most regions this app ships to. Its other four categories
        // are still empty and still need a native speaker.
        //
        // Only German is declared, and that is a REAL GAP rather than a
        // simplification: an English-language "Heil Hitler" sent to a
        // German-region reader loads `germany-en`, which does not exist, and
        // falls back to the 3 universal child patterns. uk-en happens to cover
        // that phrase, but a German reader does not get uk-en. Closing it means
        // authoring `germany-en.yaml` — the same hole as an English scam message
        // reaching a Vietnam-region reader.
        case .germany: return [.german]
        }
    }

    /// Bundle basename of this region's rule set for `language`, generated by
    /// `scripts/build_regex_patterns.py` from `guardrails/regions/<raw>-<code>.yaml`.
    func rulesResource(for language: TranslateLanguage) -> String {
        "guardrail-rules-\(rawValue)-\(language.shortCode)"
    }

    /// The set every region falls back to for a language it hasn't been authored
    /// for: the handful of patterns whose meaning doesn't move with jurisdiction
    /// or language. Baseline coverage beats no coverage.
    static let universalRulesResource = "guardrail-rules-universal"

    /// Classes this jurisdiction acts on. Anything outside the set is downgraded
    /// to Clean, whichever layer produced it.
    ///
    /// The rules alone could not express this. A rule set is written in one
    /// language, so it simply fails to match text in another — a UK reader's
    /// English patterns never fire on a Vietnamese message no matter what
    /// categories they contain. The MODEL has no such gap: it understands the
    /// language, carries its own 10-class taxonomy, and applies it identically in
    /// every region. `political` is one of those classes.
    ///
    /// So without this mask, a Vietnamese message criticising a government is
    /// flagged Political/Violation for a reader in London — where that speech is
    /// protected — because the classifier's taxonomy encodes a policy judgement
    /// that only one of our regions actually holds. Region has to gate the model's
    /// output too, or "decide locally" describes half the system.
    ///
    /// Only `political` is regional today. The other nine classes are harms
    /// everywhere we ship.
    var actionableClasses: Set<SafetyLabel> {
        switch self {
        case .vietnam:
            return Set(SafetyLabel.allCases)
        case .uk, .france, .germany, .spain:
            // Political criticism is protected expression. `uk-en.yaml` already
            // ships zero political patterns; this extends the same commitment to
            // the model, which cannot be edited the way a rule file can.
            return Set(SafetyLabel.allCases).subtracting([.political])
        }
    }

    /// ISO region code used to guess the initial selection from the device.
    private var regionCode: String {
        switch self {
        case .vietnam: return "VN"
        case .uk:      return "GB"
        case .france:  return "FR"
        case .germany: return "DE"
        case .spain:   return "ES"
        }
    }

    /// The region matching the device's own, or Vietnam when it isn't one we
    /// ship rules for.
    ///
    /// Only a DEFAULT: the device region says where the phone was set up, which
    /// is a decent first guess and a bad final answer — a user abroad, or one
    /// who simply disagrees, changes it in Settings and that choice is persisted.
    static var deviceDefault: GuardRegion {
        let code: String?
        if #available(iOS 16, *) {
            code = Locale.current.region?.identifier
        } else {
            code = Locale.current.regionCode
        }
        guard let code else { return .vietnam }
        return allCases.first { $0.regionCode == code } ?? .vietnam
    }
}
